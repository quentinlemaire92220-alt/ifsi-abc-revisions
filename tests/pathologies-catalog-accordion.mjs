import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=path=>fs.readFileSync(new URL('../'+path,import.meta.url),'utf8');
const code=read('pathologies-module-v1.js');
function part(a,b){const start=code.indexOf(a),end=code.indexOf(b,start+1);assert.ok(start>=0&&end>start,'Missing range: '+a);return code.slice(start,end);}
const ctx={};vm.createContext(ctx);
const definitions=["const P1_IDS=new Set(['bpco','hta','dt2']);",part('const P1_CATALOG=','const LABELS='),"const esc=v=>String(v??'').replace(/[&<>\"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','\"':'&quot;',\"'\":'&#39;'}[c]));","let entries=[];",part('function catalogRecords(){','function showPending('),"globalThis.exportEsc=esc;globalThis.fakeCatalog=()=>catalogRecords();globalThis.fakeMarkup=term=>catalogMarkup(catalogRecords(),term);"];
vm.runInContext(definitions.join('\n'),ctx);
const records=ctx.fakeCatalog();
assert.equal(records.length,3);
assert.deepEqual(Array.from(records.map(x=>x.id)),['bpco','hta','dt2']);
const html=ctx.fakeMarkup('');
assert.equal((html.match(/<details class=\"patho-group\"/g)||[]).length,3,'Three collapsible system panels expected');
for(const label of ['Système respiratoire','Système cardiovasculaire','Système endocrinien'])assert.ok(html.includes(label),'System absent: '+label);
for(const id of ['bpco','hta','dt2'])assert.ok(html.includes('data-patho-pending=\"'+id+'\"'),'Pending pathology not navigable: '+id);
assert.ok(html.includes('Contenu en cours de validation médicale'));
assert.ok(!html.includes('data-patho-course'),'Clicking a pathology must not open a course');
assert.ok(!html.includes('Bonne réponse'));
assert.ok(ctx.fakeMarkup('respiratoire').includes('data-patho-pending=\"bpco\"'));
assert.ok(!ctx.fakeMarkup('respiratoire').includes('data-patho-pending=\"hta\"'));
assert.ok(ctx.fakeMarkup('hypertension').includes('data-patho-pending=\"hta\"'));
assert.ok(ctx.fakeMarkup('inconnu').includes('Aucune pathologie trouvée'));
let courseOpens=0,backClicks=0,pendingMarkup='';
const fakeHost={set innerHTML(x){pendingMarkup=x;},querySelectorAll(selector){return selector==='[data-patho-course]'?[{dataset:{pathoCourse:'systeme_respiratoire'},onclick:null}]:[]}};
const backButton={onclick:null};
const pageCtx={P1_CATALOG:records,pendingId:null,state:{id:'none'},byId:id=>id==='ifsiPathologiesBody'?fakeHost:id==='pathoBack'?backButton:null,esc:ctx.exportEsc,action:(label,attr)=>'<button '+attr+'>'+label+'</button>',openLinkedCourse:()=>{courseOpens++;},list(){backClicks++;}};
vm.createContext(pageCtx);
vm.runInContext(part('function showPending(','function list(){')+'\nglobalThis.openDraft=showPending;',pageCtx);
pageCtx.openDraft('bpco');
assert.equal(courseOpens,0,'Opening BPCO must not redirect automatically to its course');
assert.ok(pendingMarkup.includes('Bronchopneumopathie chronique obstructive (BPCO)'));
assert.ok(pendingMarkup.includes('Ressources en cours de validation médicale'));
assert.ok(pendingMarkup.includes('Ouvrir le cours IFSI'),'Course remains an optional secondary action');
assert.equal(typeof backButton.onclick,'function');backButton.onclick();assert.equal(backClicks,1);
assert.ok(code.includes('results.querySelectorAll(\'[data-patho-pending]\')'),'Pending entry click missing');
assert.ok(code.includes('results.querySelectorAll(\'[data-patho-published]\')'),'Published entry click missing');
const index=read('index.html'),sw=read('sw.js');
assert.ok(!index.includes('IFSI_PATHOLOGIES_PUBLISHED_BUNDLE')&&!sw.includes('IFSI_PATHOLOGIES_PUBLISHED_BUNDLE'),'Private medical content leak');
console.log('✅ Pathologies : 3 volets dépliables, entrée sur fiche dédiée, aucune redirection automatique, contenus privés protégés.');
