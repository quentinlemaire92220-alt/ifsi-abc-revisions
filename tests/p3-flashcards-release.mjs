import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {runtimeDeck} from './flashcards-runtime-fixture.mjs';

const source=fs.readFileSync('p3-vocabulary-flashcards.js','utf8');
const sha256=createHash('sha256').update(source).digest('hex');
const approvalRecord=JSON.parse(fs.readFileSync('docs/p3-vocabulary-publication.json','utf8'));
assert.equal(approvalRecord.lotId,'p3-vocabulary-18-20261020');
assert.equal(approvalRecord.version,'8.30.103');
assert.equal(approvalRecord.scope,'18_vocabulary_supplemental_flashcards');
assert.equal(approvalRecord.cards,18);
assert.equal(approvalRecord.sourceType,'reference_pedagogique');
assert.equal(approvalRecord.evidence.directCourse+approvalRecord.evidence.partialCourse+approvalRecord.evidence.externalReference,18);
assert.equal(approvalRecord.publicationApproval.status,'approved');
assert.equal(approvalRecord.publicationApproval.authorization,'explicit_go_publication');
assert.equal(approvalRecord.publicationApproval.scope,approvalRecord.scope);
assert.ok(Number.isFinite(Date.parse(approvalRecord.publicationApproval.approvedAt)));
assert.equal(approvalRecord.publicationApproval.bundleSha256,sha256,'Le contenu pédagogique a changé depuis l’approbation');
const scope={window:{}};
vm.runInNewContext(source,scope);
const proposed=scope.window.IFSI_P3_VOCAB_FLASHCARDS;
assert.ok(proposed,'Lot P3 manquant');
const expected=['enrich_meningite','enrich_encephalite','enrich_pneumonie','enrich_virion','enrich_capside','enrich_formule_concentration','enrich_debit_perfusion','enrich_dilution','enrich_preuve_scientifique','enrich_rappel_actif','enrich_organe','enrich_tachypnee','enrich_bradycardie','enrich_tachycardie','enrich_dysphagie','enrich_anurie','enrich_polyurie','enrich_assertivite'];
assert.equal(Object.keys(proposed).length,18,'Exactement 18 propositions approuvées');
assert.deepEqual(Object.keys(proposed).sort(),[...expected].sort(),'Le lot approuvé doit être exact');
const vocab=JSON.parse(fs.readFileSync('vocabulaire-v1.json','utf8')).entries;
const questions=new Set(),ids=new Set();
const {deck}=await runtimeDeck({allCards:true});
for(const id of expected){
 const entry=vocab.find(x=>x.id===id);
 assert.ok(entry,'Terme de vocabulaire manquant: '+id);
 assert.equal(entry.sourceType,'reference_pedagogique','Le complément ne doit pas se prétendre issu du cours');
 assert.ok(entry.definition&&entry.distinction&&entry.courseIds?.length,'Données originales absentes '+id);
 const pair=proposed[id];assert.ok(Array.isArray(pair)&&pair.length===2,'Recto/verso absent '+id);
 assert.ok(pair[0].endsWith('?')&&pair[0].length>25,'Recto peu explicite '+id);
 assert.ok(pair[1].length>40,'Verso peu explicite '+id);
 assert.ok(!questions.has(pair[0]),'Deux rectos identiques '+id);
 questions.add(pair[0]);
 const card=deck.find(x=>x.id==='voc:'+id);
 assert.ok(card,'ID de flashcard supprimé '+id);ids.add(card.id);
 assert.equal(card.front,pair[0],'Recto non synchronisé '+id);
 assert.equal(card.answers[0],pair[1],'Verso non synchronisé '+id);
 assert.ok(entry.courseIds.every(c=>card.courseIds.includes(c)),'Association multi-cours perdue '+id);
 assert.equal(card.officialSupport,false,'Le supplément doit rester non officiel');
}
assert.equal(ids.size,18);
const page=fs.readFileSync('index.html','utf8');
const worker=fs.readFileSync('sw.js','utf8');
const vocabEngine=fs.readFileSync('v8355-vocabulary.js','utf8');
assert.ok(vocabEngine.includes('window.IFSI_P3_VOCAB_FLASHCARDS?.[x.id]'),'Moteur de flashcards non raccordé');
assert.ok(page.indexOf('p3-vocabulary-flashcards.js')<page.indexOf('v8355-vocabulary.js'),'Le supplément doit être chargé avant le vocabulaire');
for(const file of ['p3-vocabulary-flashcards.js','v8403-changelog.js'])assert.ok(worker.includes("'./"+file+"'"),'Cache hors-ligne absent: '+file);
assert.match(worker,/ifsi-abc-v8-30-103-local-/);
assert.equal(JSON.parse(fs.readFileSync('build-meta.json','utf8')).version,'8.30.103');
console.log('P3_CONTENT_SHA256='+sha256);
console.log('✅ P3: 18 cartes complémentaires en production, IDs et cours conservés, chargement et cache PWA présents');
