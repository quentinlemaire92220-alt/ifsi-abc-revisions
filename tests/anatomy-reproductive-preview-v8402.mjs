import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const read=p=>fs.readFileSync(p,'utf8');
const config=JSON.parse(read('docs/anatomy-reproductive-preview-v8402.json'));
const meta=JSON.parse(read('build-meta.json'));
const registry=JSON.parse(read('course-registry-v741.json'));
const audit=JSON.parse(read('resource-audit-v821.json'));
const nav=read('v82-nav-anatomy.js');
const sw=read('sw.js');
const index=read('index.html');
const home=read('v8303-home-startup.js');

assert.ok(/^8\.30\.(\d+)$/.test(meta.version)&&Number(meta.version.split('.')[2])>=102,'Version antérieure au pilote anatomique R02-R07');
assert.ok(Number(meta.build)>=8402,'Build antérieur au pilote anatomique R02-R07');
assert.equal(registry.version,meta.version);
assert.equal(audit.version,meta.version);
assert.equal(config.release,'8.30.102');
assert.equal(config.publishedAs,'PROVISIONAL_REVIEW_ONLY');
assert.equal(config.clinicalReview,'PENDING');
assert.equal(config.pedagogicalApproval,false);
assert.equal(config.officialSupport,false);
assert.equal(config.countedInHdAtlas,false);
assert.equal(config.questionsEnabled,false);
assert.equal(config.boards.length,6);
assert.equal(config.R01.status,'TO_CREATE');
assert.equal(config.R01.asset,null);
assert.equal(audit.expectedTotals.hdAtlasBoards,106);
assert.equal(Object.values(audit.atlasBoardContracts).reduce((n,v)=>n+v,0),106);
assert.equal(audit.atlasBoardContracts.systeme_reproducteur,undefined);
assert.ok(nav.includes('0 planche validée'));
assert.ok(nav.includes('6 maquettes en revue'));
assert.ok(nav.includes('ATLAS PROVISOIRE'));
assert.ok(nav.includes('NON VALIDÉE'));
assert.ok(nav.includes('data-v82repro-preview'));
assert.ok(nav.includes('v82ReproModal'));
assert.ok(index.includes('./v8402-changelog.js?v='+meta.build));
assert.ok(sw.includes("'./v8402-changelog.js'"));
assert.ok(sw.includes('"v8402-changelog.js"'));
assert.ok(home.includes('IFSI_V8402_CHANGELOG'));
assert.ok(!nav.includes('DAHYd62tg4w'), 'Private Canva design leaked');

const hashes=new Set(),paths=new Set();
for(const b of config.boards){
  assert.equal(b.isApproved,false);
  assert.equal(b.courseId,'systeme_reproducteur');
  assert.ok(b.warning.length>=18,b.id+' lacks warning');
  assert.ok(!b.path.includes('https://')&&!b.path.includes('..'));
  assert.ok(b.path.startsWith('assets/anatomy/reproductive/review/'));
  assert.ok(!paths.has(b.path));paths.add(b.path);
  assert.ok(fs.existsSync(b.path),b.id+' missing asset');
  const data=fs.readFileSync(b.path);
  assert.ok(data.length>100000&&data.length<2*1024*1024,b.id+' abnormal asset weight');
  assert.equal(data.subarray(0,3).toString('hex'),'ffd8ff',b.id+' not JPEG');
  const sha=crypto.createHash('sha256').update(data).digest('hex');
  assert.equal(sha,b.sha256,b.id+' asset SHA mismatch');
  assert.ok(!hashes.has(sha));hashes.add(sha);
  assert.ok(nav.includes('./'+b.path),b.id+' no source in UI');
  assert.ok(sw.includes("'./"+b.path+"'"),b.id+' missing in offline cache');
  assert.ok(!read('v83-anatomy-interactive.js').includes(b.path),b.id+' must not be made into anatomy quiz');
}
console.log('✅ V8.30.102 — 6 JPG de revue intégrés, empreintes vérifiées, zoom accessible, 106 planches officielles inchangées, QCM désactivés.');
