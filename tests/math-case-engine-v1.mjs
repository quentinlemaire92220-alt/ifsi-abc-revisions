import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const src=read('math-case-engine-v1.js');
const ctx={window:{},document:{readyState:'loading',addEventListener() {},getElementById(){return null;}},console};
vm.runInNewContext(src,ctx,{filename:'math-case-engine-v1.js'});
const api=ctx.window.IFSI_MATH_CASES;
assert.ok(api,'Moteur absent');
assert.equal(api.parseNumber('1 040,5'),1040.5);
assert.equal(api.parseNumber('1040.5'),1040.5);
assert.equal(api.parseNumber('3 mg'),null,'Un nombre avec unité collée doit être refusé');
assert.equal(api.parseTime('20 h 30'),'20:30');
assert.equal(api.parseTime('02:30'),'02:30');
assert.equal(api.parseTime('25:30'),null);
const numeric={id:'n',label:'Valeur',unit:'unités',type:'number',correct:12,explanation:'12 unités',commonErrors:[{when:10,feedback:'Revoir les unités'}]};
const time={id:'t',label:'Fin',unit:'HH:MM',type:'time',correct:'02:30',explanation:'Le lendemain'};
assert.equal(api.evaluate(numeric,'12').ok,true);
assert.equal(api.evaluate(numeric,'10').feedback,'Revoir les unités');
assert.equal(api.evaluate(numeric,'abc').kind,'format');
assert.equal(api.evaluate(time,'2 h 30').ok,true);
assert.equal(api.evaluate(time,'20:30').ok,false);
const sample={id:'fixture-arithmetique',courseId:'calculs_doses_mathematiques',title:'Cas fictif de test',questions:[{id:'a',prompt:'A — Question technique ?',fields:[numeric,time]}]};
assert.equal(api.validCase(sample).id,sample.id);
assert.equal(api.loadCase(sample),sample.id);
assert.equal(api.result().total,2);
assert.throws(()=>api.validCase({...sample,courseId:'autre'}));
assert.throws(()=>api.validCase({...sample,questions:[{...sample.questions[0],fields:[numeric,numeric]}]}));
const meta=JSON.parse(read('build-meta.json')),index=read('index.html'),sw=read('sw.js'),wf=read('.github/workflows/tnr.yml');
assert.ok(index.includes('./math-case-engine-v1.js?v='+meta.build),'Module absent du site');
assert.ok(sw.includes("'./math-case-engine-v1.js'"),'Module absent du cache hors ligne');
assert.ok(sw.includes('"math-case-engine-v1.js"'),'Module absent de MODULES');
assert.ok(wf.includes('node tests/math-case-engine-v1.mjs'),'Test non branché à GitHub Actions');
assert.ok(!src.includes('ue-b3-calculs-n3-ex01-private'),'Cas privé ne doit pas être versionné');
assert.ok(src.includes('type="file"')&&src.includes('f.text()'),'Import local absent');
assert.ok(src.includes('mode')&&src.includes('case-hint')&&src.includes('state.locked'),'Parcours guidé/autonome ou verrouillage absent');
assert.ok(src.includes('esc('),'Échappement HTML obligatoire');
console.log('✅ TNR calculs : source générique, saisie, unités, horaires, erreurs, import privé, cache et intégration');