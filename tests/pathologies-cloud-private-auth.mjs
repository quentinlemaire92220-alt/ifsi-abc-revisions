import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const cloud=read('pathologies-cloud-private-v1.js'),callback=read('pathologies-auth-callback-v1.js');
const html=read('index.html'),pilot=read('pilote-sources-privees.html'),sw=read('sw.js');
const storage=new Map();
const localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,String(v)),removeItem:k=>storage.delete(k)};
const pack={schema:'ifsi-abc-private-pathologies-p1-v1',reviewOnly:true,publicationPermitted:false,clinicalReview:'pending',items:[]};
const seen=[],received=[];
const fetch=async(url,options={})=>{
 seen.push({url:String(url),options});
 if(url.endsWith('/auth/v1/user'))return {ok:true,status:200,json:async()=>({id:'id-test',email_confirmed_at:'2026-10-20'})};
 if(url.includes('/rest/v1/pathologies_private_packs')){
  if(options.method==='POST'){received.push(JSON.parse(options.body));return {ok:true,status:201};}
  return {ok:true,status:200,json:async()=>[{payload:pack}]};
 }
 if(url.includes('/auth/v1/otp?'))return {ok:true,status:200};
 throw Error('Unexpected network destination: '+url);
};
const expires_at=Math.floor(Date.now()/1000)+3600;
storage.set('ifsi-pathologies-private-auth-session-v1',JSON.stringify({access_token:'signed-session-placeholder',refresh_token:'test-refresh',expires_at}));
let loaded=0;const window={localStorage,IFSI_PATHOLOGIES_REVIEW:{valid:p=>p===pack,acceptFromCloud:async p=>{assert.equal(p,pack);loaded++},getPack:()=>null},location:{hash:''}};
const ctx={window,fetch,Date,console,Promise,JSON,Math,URLSearchParams,encodeURIComponent};
vm.createContext(ctx);vm.runInContext(cloud,ctx);
const api=window.IFSI_PATHOLOGIES_CLOUD;
assert.ok(api,'Cloud module not attached');
assert.equal(api.getSession().access_token,'signed-session-placeholder');
assert.equal(await api.sync(),true,'Authenticated owner should load private pack');
assert.equal(loaded,1,'Remote pack not passed to private reader');
const get=seen.find(x=>x.url.includes('/rest/v1/'));
assert.ok(get.url.includes('pack_key=eq.p1'),'The owner-specific P1 resource is missing');
assert.equal(get.options.headers.Authorization,'Bearer signed-session-placeholder','Data query must use authenticated JWT');
assert.equal(get.options.cache,'no-store','Private packs must not use HTTP cache');
assert.equal(await api.upload(pack),true,'Owner upload should work');
assert.equal(received.length,1);
assert.equal(received[0][0].pack_key,'p1');
assert.deepEqual(received[0][0].payload,pack);
assert.equal(Object.hasOwn(received[0][0],'owner_id'),false,'Owner ID should be derived by the database JWT, never supplied by the client');
const post=seen.find(x=>x.url.includes('/rest/v1/')&&x.options.method==='POST');
assert.ok(post.options.headers.Prefer.includes('merge-duplicates'),'Upsert should be idempotent');
await api.sendLink('private@example.test');
const otp=seen.find(x=>x.url.includes('/auth/v1/otp?'));
assert.equal(JSON.parse(otp.options.body).create_user,false,'A public IFSI student must not be able to register using the private login');
assert.ok(otp.url.includes(encodeURIComponent('/pilote-sources-privees.html')),'Use only previously authorized Supabase redirect');
assert.ok(storage.has('ifsi-pathologies-private-auth-pending-v1'),'Magic Link callback must be scoped to a real sign-in request');
const removed=[],redirected=[];
const cbWindow={localStorage,location:{hash:'#access_token=aaa.bbb.ccc&refresh_token=refreshtokentesting&expires_in=3600',pathname:'/ifsi-abc-revisions/pilote-sources-privees.html',search:'',replace:url=>redirected.push(url)},history:{replaceState(...args){removed.push(args);}},document:{addEventListener(){}}};
const cbctx={localStorage,location:cbWindow.location,history:cbWindow.history,document:cbWindow.document,Date,JSON,URLSearchParams,Math};vm.createContext(cbctx);vm.runInContext(callback,cbctx);
assert.equal(redirected[0],'./index.html#pathologies','Magic Link must return to Pathologies');
assert.equal(removed.length,1,'Callback must clear tokens from address bar');
assert.equal(storage.has('ifsi-pathologies-private-auth-pending-v1'),false,'Sign-in request state must be cleared');
assert.equal(JSON.parse(storage.get('ifsi-pathologies-private-auth-session-v1')).access_token,'aaa.bbb.ccc');
assert.ok(!cloud.includes('SUPABASE_SERVICE_ROLE_KEY'),'No privileged server credential may appear in public app code');
assert.ok(!html.includes('ifsi-abc-private-pathologies-p1-v1'),'No private clinical catalogue should be embedded in index');
assert.ok(!sw.includes('IFSI_ABC_PATHOLOGIES_P1_IMPORT_PRIVE'),'No private medical pack must be pre-cached');
assert.ok(sw.includes("if(!u.pathname.endsWith('/index.html')"),'Non-app Magic Link callback must bypass service-worker app injection');
assert.ok(pilot.includes('pathologies-auth-callback-v1.js'),'Previously authorized pilot URL must receive the callback handler');
console.log('✅ Auth privée Supabase : session JWT, RLS owner, lecture, transfert, Magic Link et contrôle cache, sans pack publié.');
